/// `#RRGGBB` 글을 색 값(불투명)으로. 틀리면 null.
int? swatchValue(String hex) {
  final m = RegExp(r'^#?([0-9a-fA-F]{6})$').firstMatch(hex.trim());
  return m == null ? null : 0xFF000000 | int.parse(m.group(1)!, radix: 16);
}
